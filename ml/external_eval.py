"""External validation of the shipped checkpoint on APPA-REAL and FG-NET.

Everything in this file is **read-only with respect to the artifact**. Unlike
``eval.py``, it never stamps ``meta`` -- these are out-of-corpus numbers and must
not be written into a contract field that consumers read as the in-corpus one.

Why this exists
---------------
Our headline 4.76 MAE is measured on UTKFace, whose labels were generated by the
DEX algorithm with human review. So it is *agreement with DEX-plus-annotator*,
not error against chronological age, and no amount of in-corpus work can
separate the two. These two corpora can:

* **APPA-REAL** ships ``real_age`` (chronological, from the image owner) and
  ``apparent_age_avg`` (crowd consensus over ~38 votes). Scoring against both
  decomposes our residual into "wrong" versus "looks that age".
* **FG-NET** has real ages from dated personal photographs and ~10x the child
  density of APPA-REAL, which is where our remaining bias sits.

Method notes that matter for interpreting the output
----------------------------------------------------
APPA-REAL ships pre-cropped faces at a 40% margin. We deliberately do **not**
use them: 40% is far outside the verified safe band of roughly [0.0, 0.05], and
our own margin sweep measured a multi-year penalty out there. Feeding those
crops in would measure the crop bug, not the model. Instead we run YuNet on the
*original* images and apply the serving crop geometry at ``CROP_MARGIN = 0.0``,
matching deployment.

Decoding is the **median**, which is what the server ships. ``--decode
expectation`` reproduces the older decode for a paired comparison.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset

from data import IMAGENET_MEAN, IMAGENET_STD, INPUT_SIZE, REPO_ROOT
from measure_crop_margin import best_face, make_detector
from model import CHECKPOINT_PATH, load_checkpoint

REPORT_DIR = Path(__file__).resolve().parent / "reports"
APPA_ROOT = REPO_ROOT / "data" / "appa-real-release"
FGNET_ROOT = REPO_ROOT / "data" / "fgnet_raw" / "FGNET" / "images"

# 078A11.JPG -> subject 78, age 11. A trailing letter (e.g. 010A02a.JPG) marks a
# second scan of the same photograph; the age is unaffected.
FGNET_NAME = re.compile(r"^(\d{3})A(\d{2})([a-zA-Z]?)\.(?:jpg|JPG)$")


# --------------------------------------------------------------------------
# Serving crop geometry
# --------------------------------------------------------------------------
def square_crop(image: np.ndarray, box, margin: float) -> np.ndarray:
    """Replicate the serving crop: square of side max(w,h)*(1+2m), centred.

    Padding uses ``BORDER_REPLICATE`` for the case where the square runs off the
    frame. That is the optimistic choice -- our own padding-mode bracket found
    replicate understates the penalty relative to real background -- but at
    margin 0.0 on full images the square almost never leaves the frame, so the
    choice is close to inert here. The rate at which it *does* fire is reported
    as ``padded`` so the assumption stays visible.
    """
    x, y, w, h = box[:4]
    cx, cy = x + w / 2.0, y + h / 2.0
    side = max(w, h) * (1.0 + 2.0 * margin)
    half = side / 2.0

    left, top = int(round(cx - half)), int(round(cy - half))
    right, bottom = int(round(cx + half)), int(round(cy + half))

    height, width = image.shape[:2]
    pad_l, pad_t = max(0, -left), max(0, -top)
    pad_r, pad_b = max(0, right - width), max(0, bottom - height)
    padded = pad_l or pad_t or pad_r or pad_b

    if padded:
        image = cv2.copyMakeBorder(
            image, pad_t, pad_b, pad_l, pad_r, cv2.BORDER_REPLICATE
        )
        left, right = left + pad_l, right + pad_l
        top, bottom = top + pad_t, bottom + pad_t

    crop = image[top:bottom, left:right]
    if crop.size == 0:
        return None, padded
    return crop, padded


def detect_and_crop(detector, path: Path, margin: float):
    """Return ``(rgb_crop, info)``; ``rgb_crop`` is None when detection fails."""
    image = cv2.imread(str(path), cv2.IMREAD_COLOR)
    if image is None:
        return None, {"status": "unreadable"}

    face = best_face(detector, image)
    if face is None:
        return None, {"status": "no_face"}

    crop, padded = square_crop(image, face, margin)
    if crop is None:
        return None, {"status": "empty_crop"}

    height, width = image.shape[:2]
    return cv2.cvtColor(crop, cv2.COLOR_BGR2RGB), {
        "status": "ok",
        "score": float(face[14]),
        "det_side": float(max(face[2], face[3])),
        # Face size relative to the frame: FG-NET scans and APPA snapshots frame
        # faces very differently, and that is a domain shift worth measuring.
        "face_frac": float(max(face[2], face[3]) / max(height, width)),
        "padded": bool(padded),
    }


class DetectedFaceDataset(Dataset):
    """Detect, crop and normalise on the fly. Rows with no face yield a flag."""

    def __init__(self, rows: pd.DataFrame, margin: float, score_threshold: float):
        self.rows = rows.reset_index(drop=True)
        self.margin = margin
        self.score_threshold = score_threshold
        self._detector = None
        self.mean = np.array(IMAGENET_MEAN, dtype=np.float32).reshape(3, 1, 1)
        self.std = np.array(IMAGENET_STD, dtype=np.float32).reshape(3, 1, 1)

    def __len__(self) -> int:
        return len(self.rows)

    def _get_detector(self):
        # cv2 detectors are not fork-safe; build lazily, per worker.
        if self._detector is None:
            self._detector = make_detector(self.score_threshold)
        return self._detector

    def __getitem__(self, index: int):
        row = self.rows.iloc[index]
        crop, info = detect_and_crop(
            self._get_detector(), Path(row["path"]), self.margin
        )
        if crop is None:
            blank = torch.zeros(3, INPUT_SIZE, INPUT_SIZE)
            return blank, False, index, 0.0, 0.0

        # PIL resize to match the training/eval transform exactly. Our own
        # control run against the server measured cv2-vs-PIL resize at 0.009
        # years, so this is not free-floating -- it is the verified path.
        pil = Image.fromarray(crop).resize(
            (INPUT_SIZE, INPUT_SIZE), Image.Resampling.BILINEAR
        )
        array = np.asarray(pil, dtype=np.float32).transpose(2, 0, 1) / 255.0
        tensor = torch.from_numpy((array - self.mean) / self.std)
        return tensor, True, index, info["face_frac"], float(info["padded"])


# --------------------------------------------------------------------------
# Dataset adapters
# --------------------------------------------------------------------------
def load_appa(root: Path = APPA_ROOT) -> pd.DataFrame:
    """Original (uncropped) images joined to real and apparent age labels."""
    frames = []
    for split in ("train", "valid", "test"):
        csv = root / f"gt_avg_{split}.csv"
        if not csv.exists():
            continue
        table = pd.read_csv(csv)
        table["split"] = split
        table["path"] = table["file_name"].map(lambda n: str(root / split / n))
        frames.append(table)

    if not frames:
        raise FileNotFoundError(f"No APPA-REAL gt_avg_*.csv under {root}")

    data = pd.concat(frames, ignore_index=True)
    data = data.rename(
        columns={"real_age": "real_age", "apparent_age_avg": "apparent_age"}
    )
    data["exists"] = data["path"].map(lambda p: Path(p).exists())
    missing = int((~data["exists"]).sum())
    if missing:
        print(f"  warning: {missing} APPA-REAL images listed in GT but not on disk")
    data = data[data["exists"]].drop(columns="exists").reset_index(drop=True)
    return data


def load_fgnet(root: Path = FGNET_ROOT) -> pd.DataFrame:
    """Ages parsed from FG-NET filenames; malformed names are skipped loudly."""
    rows, skipped = [], []
    for path in sorted(root.iterdir()):
        match = FGNET_NAME.match(path.name)
        if not match:
            skipped.append(path.name)
            continue
        rows.append(
            {
                "path": str(path),
                "subject": int(match.group(1)),
                "real_age": int(match.group(2)),
                "file_name": path.name,
            }
        )
    if skipped:
        print(f"  warning: skipped {len(skipped)} unparseable FG-NET names")
        print(f"           e.g. {skipped[:5]}")
    return pd.DataFrame(rows)


# --------------------------------------------------------------------------
# Inference + metrics
# --------------------------------------------------------------------------
@torch.no_grad()
def predict(model, rows, margin, device, batch_size, workers, score_threshold, decode):
    loader = DataLoader(
        DetectedFaceDataset(rows, margin, score_threshold),
        batch_size=batch_size,
        shuffle=False,
        num_workers=workers,
        pin_memory=False,
    )

    n = len(rows)
    preds = np.full(n, np.nan, dtype=np.float64)
    spread = np.full(n, np.nan, dtype=np.float64)
    found = np.zeros(n, dtype=bool)
    face_frac = np.full(n, np.nan, dtype=np.float64)
    padded = np.zeros(n, dtype=bool)

    done = 0
    for images, ok, index, frac, pad in loader:
        images = images.to(device, non_blocking=True)
        logits = model(images)
        if decode == "median":
            age, unc = model.median(logits)
        else:
            age, unc = model.expectation(logits)

        index = index.numpy()
        ok = ok.numpy().astype(bool)
        preds[index] = age.float().cpu().numpy()
        spread[index] = unc.float().cpu().numpy()
        found[index] = ok
        face_frac[index] = frac.numpy()
        padded[index] = pad.numpy().astype(bool)

        done += len(index)
        if done % (batch_size * 10) < batch_size:
            print(f"    {done}/{n}", end="\r", flush=True)

    out = rows.copy().reset_index(drop=True)
    out["predicted"] = preds
    out["spread"] = spread
    out["detected"] = found
    out["face_frac"] = face_frac
    out["padded"] = padded
    return out


def metrics_against(frame: pd.DataFrame, target: str) -> dict:
    """MAE / CS@5 / bias of ``predicted`` against ``target``, detected rows only."""
    valid = frame[frame["detected"] & frame[target].notna()]
    if valid.empty:
        return {"n": 0}
    error = valid["predicted"].to_numpy() - valid[target].to_numpy()
    return {
        "n": int(len(valid)),
        "mae": float(np.abs(error).mean()),
        "cs5": float((np.abs(error) <= 5).mean() * 100.0),
        "rmse": float(np.sqrt((error**2).mean())),
        "bias": float(error.mean()),
    }


def decade_table(frame: pd.DataFrame, target: str) -> pd.DataFrame:
    """Per-decade MAE conditioned on ``target``. See eval.py on conditioning."""
    valid = frame[frame["detected"] & frame[target].notna()].copy()
    edges = [0, 10, 20, 30, 40, 50, 60, 70, 80, 200]
    labels = [
        "0-9", "10-19", "20-29", "30-39", "40-49",
        "50-59", "60-69", "70-79", "80+",
    ]
    valid["decade"] = pd.cut(
        valid[target], bins=edges, labels=labels, right=False, include_lowest=True
    )
    error = valid["predicted"] - valid[target]
    valid["abs_error"] = error.abs()
    valid["signed"] = error

    table = (
        valid.groupby("decade", observed=False)
        .agg(
            n=("abs_error", "size"),
            mae=("abs_error", "mean"),
            bias=("signed", "mean"),
        )
        .reset_index()
    )
    return table[table["n"] > 0]


def human_gap_table(frame: pd.DataFrame) -> pd.DataFrame:
    """Human error on the same images: |apparent_age_avg - real_age| per decade.

    This is the comparison that reframes the elderly result. Our model's error
    against ``real_age`` is only damning if humans do better on the same faces.
    """
    valid = frame[frame["real_age"].notna() & frame["apparent_age"].notna()].copy()
    edges = [0, 10, 20, 30, 40, 50, 60, 70, 80, 200]
    labels = [
        "0-9", "10-19", "20-29", "30-39", "40-49",
        "50-59", "60-69", "70-79", "80+",
    ]
    valid["decade"] = pd.cut(
        valid["real_age"], bins=edges, labels=labels, right=False, include_lowest=True
    )
    gap = valid["apparent_age"] - valid["real_age"]
    valid["human_abs"] = gap.abs()
    valid["human_bias"] = gap

    table = (
        valid.groupby("decade", observed=False)
        .agg(
            n=("human_abs", "size"),
            human_mae=("human_abs", "mean"),
            human_bias=("human_bias", "mean"),
        )
        .reset_index()
    )
    return table[table["n"] > 0]


def print_table(frame: pd.DataFrame, columns: dict[str, str]) -> None:
    header = "".join(f"{label:>12}" for label in columns.values())
    print(f"  {'bin':<8}{header}")
    print(f"  {'-' * (8 + 12 * len(columns))}")
    for _, row in frame.iterrows():
        cells = ""
        for key in columns:
            value = row[key]
            cells += (
                f"{int(value):>12}"
                if key == "n"
                else f"{value:>12.2f}"
            )
        print(f"  {str(row.iloc[0]):<8}{cells}")


def sweep_margins(model, rows, margins, device, batch_size, score_threshold,
                  decode, targets):
    """MAE across several crop margins, reusing one set of detections.

    YuNet's box does not depend on our crop margin, so detecting once and
    re-cropping is exactly equivalent to re-running detection per margin and is
    several times faster -- detection dominates the cost on full-size photos.

    This matters beyond speed. Our margin constant was verified on UTKFace,
    whose images are already tight 200x200 crops. APPA-REAL photos are full
    scenes, which is the condition the constant was never tested under.
    """
    detector = make_detector(score_threshold)
    boxes, images = {}, {}
    for position, (_, row) in enumerate(rows.iterrows()):
        image = cv2.imread(row["path"], cv2.IMREAD_COLOR)
        if image is None:
            continue
        face = best_face(detector, image)
        if face is None:
            continue
        boxes[position] = face[:4].astype(float)
        images[position] = image
        if position % 500 == 0:
            print(f"    detect {position}/{len(rows)}", end="\r", flush=True)
    print(f"    detected {len(boxes)}/{len(rows)}          ")

    mean = np.array(IMAGENET_MEAN, dtype=np.float32).reshape(3, 1, 1)
    std = np.array(IMAGENET_STD, dtype=np.float32).reshape(3, 1, 1)
    results = {}

    for margin in margins:
        batch, positions, preds = [], [], []

        def flush():
            if not batch:
                return
            with torch.no_grad():
                tensor = torch.from_numpy(np.stack(batch)).to(device)
                logits = model(tensor)
                age = (model.median(logits)[0] if decode == "median"
                       else model.expectation(logits)[0])
            preds.append(age.float().cpu().numpy())

        for position, box in boxes.items():
            crop, _ = square_crop(images[position], box, margin)
            if crop is None:
                continue
            pil = Image.fromarray(cv2.cvtColor(crop, cv2.COLOR_BGR2RGB)).resize(
                (INPUT_SIZE, INPUT_SIZE), Image.Resampling.BILINEAR
            )
            array = np.asarray(pil, dtype=np.float32).transpose(2, 0, 1) / 255.0
            batch.append((array - mean) / std)
            positions.append(position)
            if len(batch) == batch_size:
                flush()
                batch = []
        flush()

        predicted = np.concatenate(preds)
        subset = rows.iloc[positions]
        entry = {}
        for target in targets:
            error = predicted - subset[target].to_numpy(dtype=float)
            entry[target] = {
                "mae": float(np.abs(error).mean()),
                "cs5": float((np.abs(error) <= 5).mean() * 100),
                "bias": float(error.mean()),
            }
        results[f"{margin:.4f}"] = entry
        cells = "".join(f"{entry[t]['mae']:>16.3f}" for t in targets)
        print(f"  {margin:>8.3f}{cells}")

    return results


def main() -> None:
    parser = argparse.ArgumentParser(description="External validation")
    parser.add_argument(
        "--datasets", nargs="*", default=["appa", "fgnet"],
        choices=["appa", "fgnet"],
    )
    parser.add_argument("--checkpoint", type=Path, default=CHECKPOINT_PATH)
    parser.add_argument("--margin", type=float, default=0.0)
    parser.add_argument("--decode", default="median", choices=["median", "expectation"])
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--score-threshold", type=float, default=0.6)
    parser.add_argument("--limit", type=int, default=0, help="debug: cap rows")
    parser.add_argument(
        "--sweep-margins", type=float, nargs="*", default=None,
        help="re-crop at several margins from one set of detections",
    )
    parser.add_argument("--device", default=None)
    args = parser.parse_args()

    device = torch.device(
        args.device
        or ("mps" if torch.backends.mps.is_available() else "cpu")
    )
    model, meta = load_checkpoint(args.checkpoint, map_location=device)
    model.to(device)
    model.eval()

    print(f"Checkpoint : {args.checkpoint}")
    print(f"Decode     : {args.decode}   margin: {args.margin}   device: {device}")
    print(f"meta.test_mae (in-corpus, expectation decode): {meta.get('test_mae')}")
    print()

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    summary = {
        "checkpoint": str(args.checkpoint),
        "decode": args.decode,
        "margin": args.margin,
        "detector": "YuNet 2023mar",
        "score_threshold": args.score_threshold,
        "datasets": {},
    }

    for name in args.datasets:
        print(f"=== {name.upper()} ===")
        rows = load_appa() if name == "appa" else load_fgnet()
        if name == "appa" and args.sweep_margins is not None:
            # Sweep on the held-out split so the curve is not read off data the
            # constant could have been tuned on.
            rows = rows[rows["split"] == "test"].reset_index(drop=True)
        if args.limit:
            rows = rows.head(args.limit)
        print(f"  images: {len(rows)}")

        targets = ["real_age", "apparent_age"] if name == "appa" else ["real_age"]

        if args.sweep_margins is not None:
            print(f"\n  -- crop-margin sweep ({len(args.sweep_margins)} points) --")
            header = "".join(f"{t:>16}" for t in targets)
            print(f"  {'margin':>8}{header}")
            sweep = sweep_margins(
                model, rows, args.sweep_margins, device, args.batch_size,
                args.score_threshold, args.decode, targets,
            )
            path = REPORT_DIR / f"external_margin_sweep_{name}_{args.decode}.json"
            path.write_text(json.dumps(sweep, indent=2) + "\n")
            print(f"  sweep -> {path.relative_to(REPO_ROOT)}\n")
            summary["datasets"][name] = {"margin_sweep": sweep}
            continue

        result = predict(
            model, rows, args.margin, device, args.batch_size,
            args.workers, args.score_threshold, args.decode,
        )

        detected = int(result["detected"].sum())
        fail_rate = 100.0 * (1 - detected / len(result))
        print(f"  detected: {detected}/{len(result)}  "
              f"(failure rate {fail_rate:.2f}%)")
        padded_rate = 100.0 * result.loc[result["detected"], "padded"].mean()
        print(f"  crops needing pad: {padded_rate:.2f}%")

        entry = {
            "n_images": int(len(result)),
            "n_detected": detected,
            "detection_failure_rate": fail_rate,
            "padded_rate": float(padded_rate),
            "median_face_frac": float(
                result.loc[result["detected"], "face_frac"].median()
            ),
        }

        for target in targets:
            if target not in result.columns:
                continue
            stats = metrics_against(result, target)
            entry[target] = stats
            print(f"\n  -- vs {target} --")
            print(f"  MAE {stats['mae']:.3f}   CS@5 {stats['cs5']:.2f}%   "
                  f"RMSE {stats['rmse']:.3f}   bias {stats['bias']:+.3f}")
            table = decade_table(result, target)
            entry[f"{target}_by_decade"] = table.to_dict(orient="records")
            print_table(table, {"n": "n", "mae": "MAE", "bias": "bias"})

        if name == "appa":
            human = human_gap_table(result)
            entry["human_gap_by_decade"] = human.to_dict(orient="records")
            overall_gap = float(
                (result["apparent_age"] - result["real_age"]).abs().mean()
            )
            entry["human_gap_overall"] = overall_gap
            print(f"\n  -- human |apparent - real| on the same images --")
            print(f"  overall {overall_gap:.3f} years")
            print_table(
                human, {"n": "n", "human_mae": "humanMAE", "human_bias": "humanBias"}
            )

        dump = REPORT_DIR / f"external_{name}_{args.decode}.csv"
        keep = [c for c in (
            "file_name", "path", "subject", "real_age", "apparent_age",
            "predicted", "spread", "detected", "face_frac", "padded", "split",
        ) if c in result.columns]
        result[keep].to_csv(dump, index=False)
        print(f"\n  per-sample dump -> {dump.relative_to(REPO_ROOT)}\n")
        summary["datasets"][name] = entry

    # Sweep mode writes its own summary so a sweep can never clobber the full
    # evaluation's metrics, which are the numbers the report quotes.
    stem = "external_sweep" if args.sweep_margins is not None else "external_validation"
    out = REPORT_DIR / f"{stem}_{args.decode}.json"
    out.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"Summary -> {out.relative_to(REPO_ROOT)}")
    print("\nNote: the checkpoint was not modified. These are out-of-corpus")
    print("numbers and must not be stamped into meta['test_mae'].")


if __name__ == "__main__":
    main()
